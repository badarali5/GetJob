CREATE OR REPLACE PROCEDURE public.archive_old_saved_jobs(IN p_days integer DEFAULT 90)
LANGUAGE plpgsql
AS $$
BEGIN
	INSERT INTO public.saved_jobs_archive (saved_job_id, user_id, job_id, saved_at, archived_at, archive_reason)
	SELECT s.id, s.user_id, s.job_id, s.saved_at, CURRENT_TIMESTAMP, 'Older than ' || p_days || ' days'
	FROM public.saved_jobs s
	WHERE s.saved_at < CURRENT_TIMESTAMP - make_interval(days => p_days)
	ON CONFLICT (saved_job_id) DO UPDATE
		SET user_id = EXCLUDED.user_id,
			job_id = EXCLUDED.job_id,
			saved_at = EXCLUDED.saved_at,
			archived_at = EXCLUDED.archived_at,
			archive_reason = EXCLUDED.archive_reason;

	DELETE FROM public.saved_jobs
	WHERE saved_at < CURRENT_TIMESTAMP - make_interval(days => p_days);
END;
$$;

