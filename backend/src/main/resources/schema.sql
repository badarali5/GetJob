$$;

CREATE OR REPLACE FUNCTION public.audit_application_changes()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
	IF TG_OP = 'INSERT' THEN
		INSERT INTO public.application_audit (application_id, user_id, job_id, action_type, details)
		VALUES (NEW.id, NEW.user_id, NEW.job_id, 'INSERT', 'Application created');
		RETURN NEW;
	ELSIF TG_OP = 'UPDATE' THEN
		INSERT INTO public.application_audit (application_id, user_id, job_id, action_type, details)
		VALUES (NEW.id, NEW.user_id, NEW.job_id, 'UPDATE', 'Application updated');
		RETURN NEW;
	ELSIF TG_OP = 'DELETE' THEN
		INSERT INTO public.application_audit (application_id, user_id, job_id, action_type, details)
		VALUES (OLD.id, OLD.user_id, OLD.job_id, 'DELETE', 'Application deleted');
		RETURN OLD;
	END IF;

	RETURN NULL;
END;
$$;

