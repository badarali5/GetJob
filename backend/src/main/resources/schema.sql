CREATE OR REPLACE FUNCTION public.sync_job_company()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
	normalized_company_name character varying(150);
BEGIN
	normalized_company_name := NULLIF(btrim(COALESCE(NEW.company_name, '')), '');

	IF normalized_company_name IS NULL THEN
		normalized_company_name := 'Unspecified';
	END IF;

	NEW.company_name := normalized_company_name;

	SELECT c.id
	INTO NEW.company_id
	FROM public.company c
	WHERE c.name = normalized_company_name
	LIMIT 1;

	IF NEW.company_id IS NULL THEN
		INSERT INTO public.company (name)
		VALUES (normalized_company_name)
		RETURNING id INTO NEW.company_id;
	END IF;

	RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.ensure_event_timestamp()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
	IF TG_TABLE_NAME = 'applications' THEN
		NEW.applied_at := COALESCE(NEW.applied_at, CURRENT_TIMESTAMP);
	ELSIF TG_TABLE_NAME = 'saved_jobs' THEN
		NEW.saved_at := COALESCE(NEW.saved_at, CURRENT_TIMESTAMP);
	END IF;

	RETURN NEW;
END;
$$;

